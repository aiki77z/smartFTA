# 改进版：增强实体和关系提取的全面性，在不改变关系类型的前提下提升提取数量

def generate_entity_prompt_and_context(chunk_name, chunk_content: str, max_name_len: int = 30):
    domain = chunk_name.split('_')[0]
    
    # 扩展实体类别定义，明确要求提取所有可能的故障相关实体
    entity_category_definition = {
        "故障原因与现象": """指任何与故障相关的实体，包括但不限于：
- 宏观故障（系统级别的异常，如控制单元硬件故障、功率单元故障、编码器及传感器故障等）
- 故障现象（设备表现出的异常行为、报警、错误提示）
- 故障原因（导致故障的根本原因，如硬件损坏、软件错误、配置不当、环境因素）
- 报警号/错误码（如 ALM401、E-101、0x8000、F01000）
- 异常状态（如温度过高、电压不稳、通信超时、资源耗尽）
- 故障部件（如电源模块、控制单元、传感器）
- 故障条件（如输入电压低于阈值、湿度超过90%）
- **文档章节标题中描述的故障类别**（例如：“功率单元及电机模块硬件故障”、“控制单元硬件故障”）
- **任何动词短语描述的异常事件**（如“电机无法启动”、“通信中断”、“参数丢失”）

**提取要求**：只要文档中提及了可能导致或已经导致系统异常的因素、表现、事件，无论是否显式标记为“故障”，都应提取为“故障原因与现象”。即使只出现一次也要提取。""",
        
        "逻辑与": """指两个或以上“故障原因与现象”同时存在、共同作用导致另一个故障的逻辑组合。
实体名称可以用“&”或“+”连接多个故障名称，例如“电源无法接通 & ALM401”或“温度过高+风扇停转”。
如果组合名称过长，可以适当缩写或取关键部分，但应保持语义清晰。
**注意**：当文本中出现“A和B同时发生导致C”、“A、B共同引起C”、“A伴随B出现”等表述时，必须创建“逻辑与”实体，并将A、B与之关联。"""
    }
    
    entity_defs = '\n'.join([f"- {k}:\n    {v}" for k, v in entity_category_definition.items()])

    context = f"""你是一位资深的"{domain}"领域专家，特别擅长从技术文档中全面、精确地提取所有与故障相关的实体。
当前任务需要严格遵循以下规则：
1. **必须提取文档中出现的所有故障现象、故障原因、报警号、错误码、异常状态、故障部件、故障条件等，不要遗漏任何可能对故障分析有帮助的实体。** 即使实体只出现一次，也要提取。
2. **特别重要：必须从文档的章节标题（如“章: xxx”、“节: xxx”、“小节: xxx”、“章节路径: xxx”）中提取故障类别实体。** 例如：
   - 标题“2.2 功率单元及电机模块（MM）硬件故障数据” → 提取实体“功率单元及电机模块硬件故障”
   - 标题“2.1 控制单元（CU）硬件故障数据” → 提取实体“控制单元硬件故障”
   对于这类实体，其描述可以概括为“该类故障涉及XX组件的硬件异常”，排查/修复方法可概括通用步骤。
3. 实体类型分为两类：“故障原因与现象”和“逻辑与”。
   - 对于单个故障相关的实体（包括从标题提取的故障类别），统一归类为“故障原因与现象”。
4. 实体名称长度不超过{max_name_len}字符。尽量使用原文中的原始表述，可去除冗余词语（如“数据”、“说明”、“汇总”），但保留核心故障含义。
5. 必须从原文中提取或合理归纳以下字段：
   - description: 对该实体的详细描述（现象、原因、影响等）
   - rule: 排查或判断该实体相关问题的规则（例如“当出现XX时，应优先检查YY”）
   - investigateMethod: 调查/诊断该实体的具体方法（步骤、工具、测量点等）
   - repairMethod: 修复/解决该实体相关故障的方法
6. 如果某字段在原文中没有明确信息，可以结合你的领域知识合理补充，但不要编造与原文矛盾的内容。若实在无法提取，保留空字符串""。
7. 输出格式：严格的JSON对象，包含"entities"数组，每个元素格式如下：
   {{
     "name": "实体名称",
     "entity_type": "故障原因与现象 或 逻辑与",
     "description": "描述文本",
     "rule": "排查规则",
     "investigateMethod": "调查方法",
     "repairMethod": "修复方法"
   }}
8. **注意：实体可能出现在标题上，对于标题进行重点分析，尤其是以“章:”、“节:”、“小节:”开头的行。**
9. **实体数量要求：请尽可能多地提取实体。如果文本较长，至少提取5个以上实体。不要因为谨慎而漏掉任何可能相关的实体。**
10. 只输出JSON，不要有任何解释文字、前缀或后缀。"""

    prompt = f"""请从以下<{domain}>技术文档片段中提取所有可能的故障原因、故障现象、报警号、错误码、异常状态、故障条件、**以及从章节标题中提取的故障类别**等实体，并严格遵守JSON输出格式。

<实体类别定义>
{entity_defs}

<输出示例>
{{
  "entities": [
    {{
      "name": "控制单元硬件故障",
      "entity_type": "故障原因与现象",
      "description": "控制单元（CU）硬件异常，包括内部软件错误、存储器访问延迟、DRIVE-CLiQ组件属性变化等",
      "rule": "出现F01000、F01002等故障代码时，优先检查控制单元电源和固件版本",
      "investigateMethod": "读取故障缓冲器r0945，检查控制单元主板状态",
      "repairMethod": "重新上电，升级固件，必要时更换控制单元"
    }},
    {{
      "name": "电源无法接通",
      "entity_type": "故障原因与现象",
      "description": "设备上电后电源指示灯不亮，无法正常启动",
      "rule": "当出现电源无法接通时，优先检查保险丝、电源线和输入电压",
      "investigateMethod": "使用万用表测量电源模块输入端电压，检查保险丝是否熔断",
      "repairMethod": "更换熔断的保险丝，修复或更换损坏的电源线"
    }},
    {{
      "name": "ALM401",
      "entity_type": "故障原因与现象",
      "description": "伺服驱动器报警代码，表示编码器通信异常",
      "rule": "出现ALM401时，检查编码器连接线和驱动器参数设置",
      "investigateMethod": "检查编码器线缆是否断路或接触不良，使用示波器测量通信波形",
      "repairMethod": "重新插拔或更换编码器线缆，调整驱动器参数"
    }},
    {{
      "name": "电源无法接通 & ALM401",
      "entity_type": "逻辑与",
      "description": "电源无法接通和ALM401报警同时发生，导致系统完全停机",
      "rule": "同时出现两种现象时，需重点检查电源模块和编码器共用线路",
      "investigateMethod": "先排除电源故障，再检查编码器供电及信号回路",
      "repairMethod": "更换电源模块，同时更换编码器线缆"
    }}
  ]
}}

<待分析文本>
{chunk_content}
"""
    return prompt, context


def generate_relation_prompt_and_context_second(chunk_name, chunk_content: str, entities):
    """
    entities: List[dict] with keys: entity_name, entity_type
    所有实体均可参与关系提取
    """
    domain = chunk_name.split('_')[0]

    context = f"""你是一位资深的"{domain}"领域专家，特别擅长从技术文档中识别故障原因与现象之间的因果关系、故障原因与现象与逻辑组合之间的关联。
当前任务需要严格遵循以下规则：
1. 关系必须基于文本中的表达（因果动词、并列组合、顺序逻辑等）
2. 每个关系必须连接两个已识别实体
3. 所有关系动词应来自文本中的明确含义，可以适度归纳总结（例如“A导致B”可归纳为“导致”）
4. 不允许虚构关系或凭空假设（必须在上下文中有依据）
5. 必须严格使用提供的实体和关系类型
6. **重要：请尽可能多地提取关系，不要遗漏任何合理的因果链或组合关系。**
7. **方向规则：因果关系方向必须是从原因指向结果，从子类指向大类，从具体指向抽象。** 例如，若文本表明“A是B的一种表现”或“A导致B”，则提取为 A → B，绝不能反向。"""

    predefined_relations = """
<实体类型关系参考框架>
本任务仅提取以下三类关系，其他关系一律忽略：

1. 故障原因与现象 → 逻辑与 (Relation: 参与组合)
定义：当多个故障原因与现象（实体类型为“故障原因与现象”）共同导致另一个故障时，每个故障原因与现象与该“逻辑与”实体之间的关系。
典型动词：同时发生、共同出现、一起发生、组合、与…结合、并列出现等归纳为“参与组合”
方向：故障原因与现象在前，逻辑与在后
示例：<电源无法接通, 参与组合, 同时发生, 逻辑与_电源ALM>

2. 逻辑与 → 故障原因与现象 (Relation: 组合导致)
定义：由多个故障原因与现象组合而成的“逻辑与”实体所导致的结果故障原因与现象（实体类型为“故障原因与现象”）。
典型动词：导致、引起、造成、触发、产生等归纳为“导致”
方向：逻辑与在前，故障原因与现象在后
示例：<逻辑与_电源ALM, 组合导致, 导致, 系统死机>

3. 故障原因与现象 → 故障原因与现象 (Relation: 触发)
定义：单个故障原因与现象直接导致另一个故障原因与现象的单步因果关系。
典型动词：导致、引起、造成、触发、产生、引发、源于、由…引起、…的故障原因与现象为…等归纳为“触发”
方向：原因故障在前，结果故障在后
**特别说明：当文本中表明某个具体故障是大类故障的一种表现、子类或组成部分时（例如“电机过载属于功率单元故障”），应提取为具体故障 → 大类故障。** 即：子故障（具体）触发大类故障（抽象）。
示例：
- <熔断器烧断, 触发, 导致, 电源无法接通>
- <电机过载, 触发, 属于, 功率单元故障>
- <编码器信号丢失, 触发, 引起, 控制单元报警>
"""

    entity_list = '\n'.join([
        f"- {e.get('entity_name') or e.get('name')} ({e.get('entity_type')})"
        + (f" [来源: {e.get('origin')}]" if e.get("origin") else "")
        for e in entities
    ]) or "(无实体，请直接输出空)"

    prompt = f"""请从以下<{domain}>技术文档片段中，基于提供的实体列表，**穷尽式地**提取上述三类关系（参与组合、组合导致、触发）。

**方向强制规则（必须遵守）：**
- 对于“触发”关系，方向永远是：原因 → 结果，子类 → 大类，具体 → 抽象。**禁止反向提取**（例如不能提取“大类故障触发子故障”）。
- 如果文本说“A是B的一种”、“A属于B”、“A表现为B”、“A导致B”，一律提取为 <A, 触发, 相应动词, B>。
- 如果文本说“B包括A”、“B由A引起”，同样提取为 <A, 触发, 引起, B>。
- 当你不确定方向时，记住：**具体的、先发生的、原因性的实体放在左边，抽象的、后发生的、结果性的实体放在右边。**

<实体列表>
{entity_list}

<关系规范>
{predefined_relations}

<关系提取规则（重要）>
1. 每个关系必须在文本中能找到明确语义或上下文逻辑。对于隐含的因果关系（如“A后出现B”、“A引起B”），也必须提取。
2. 返回的实体必须完全匹配提供的实体列表中的名称。若文本中的表述与实体名称略有差异，以实体列表中的名称为准。
3. 输出四元组格式如下（**每行一个关系，不要输出任何其他内容**）：
   <实体1, 关系类型, 具体动词, 实体2>
4. 示例（假设实体列表包含：电源无法接通、ALM401、主轴过载、逻辑与_电源ALM、电机过载、功率单元故障）：
   <电源无法接通, 参与组合, 同时发生, 逻辑与_电源ALM>
   <ALM401, 参与组合, 同时发生, 逻辑与_电源ALM>
   <逻辑与_电源ALM, 组合导致, 导致, 主轴过载>
   <熔断器烧断, 触发, 导致, 电源无法接通>
   <电机过载, 触发, 属于, 功率单元故障>
   <编码器异常, 触发, 引起, 控制单元故障>
5. **鼓励提取所有可能的关系**：如果文本中有多个因果链，请全部输出。特别是当多个具体故障都属于一个大类故障时，应为每个具体故障提取一条“触发”关系指向大类故障。
6. 如果文本中没有“逻辑与”实体，则只提取“触发”关系。
7. **不要因为关系数量多而省略。一段技术文档中往往有多个因果关系，请仔细分析每个句子，确保方向正确。**
8. 如果待分析文本包含“【前文上下文 CONTEXT】”和“【当前处理文本 TARGET】”：
   - CONTEXT 只用于理解 TARGET 中的指代、省略和跨 Chunk 边界的直接关系；
   - 可以输出“CONTEXT 中实体”与“TARGET 中实体”之间、且必须结合 TARGET 才成立的直接关系；
   - 可以输出 TARGET 内部直接支持的关系；
   - 禁止输出只依赖 CONTEXT 就能成立的旧关系；
   - 禁止进行多跳传递推理，例如 A 导致 B、B 导致 C 时，不得额外输出 A 导致 C；
   - 遇到“该故障、上述现象、此问题、该部件、前述报警”等指代表达时，优先解析到实体列表中的具体实体，不要把指代表达创建为新实体。

<待分析文本>
{chunk_content}
"""
    return prompt, context
