def generate_entity_prompt_and_context(chunk_name, chunk_content: str):
    domain = chunk_name.split('_')[0]
    # 定义两类实体：故障现象与报警、逻辑与
    entity_category_definition = {
        "故障现象与报警": "指系统或设备在运行中出现的具体故障现象、报警号及其含义（如：电源无法接通、ALM401、ALM380500）",
        "逻辑与": "指多个故障现象同时存在并共同导致另一故障的逻辑组合关系。实体名称由这些故障现象的名称用'&'连接构成（如：电源无法接通 & ALM401），长度≤20字符，若超长则取前几个故障现象或使用缩写"
    }
    entity_defs = '\n'.join([f"- {k}: {v}" for k, v in entity_category_definition.items()])

    context = f"""你是一位资深的"{domain}"领域专家，特别擅长从技术文档中精确提取专业实体。
当前任务需要严格遵循以下规则：
1. 实体必须属于以下两类之一：
   - 故障现象与报警：系统或设备运行中出现的具体故障现象、报警号及其含义。
   - 逻辑与：当文档明确描述多个故障现象（如A、B、C）共同导致另一故障D时，为这些故障现象（A、B、C）提取一个“逻辑与”实体。
2. 实体名称必须是有明确含义的专业技术术语。
3. 不允许抽取泛化、模糊、不具体或无法单独使用的词语。
4. 禁止抽取的模糊或泛化词汇（包括但不限于）：
   - 无法独立指代具体现象或报警的抽象名词（如：结构、特性、形状、浓度、规范要求）
   - 泛指词汇未被清晰技术修饰（如“设备”“系统”“条件”）
   - 动作或管理性短语（如：技术培训、排除故障）
5. 禁止抽取纯动词或动词化结构（如“添加”“分析”），但允许描述故障状态的名词性短语（如“电源无法接通”）。
6. “逻辑与”实体提取条件：
   - 原文中必须存在明确的因果或共同导致关系，例如：“A和B同时发生导致C”“A、B共同引起D”“当A与B均出现时，发生C”。
   - 只对“导致另一故障”的那一组前因故障现象提取逻辑与实体，不提取结果故障。
   - 实体名称格式：故障现象1 & 故障现象2 & 故障现象3（若超过3个或总长度>20字符，可只取前两个加“等”，如“A & B 等”）。
   - 不允许随意组合无逻辑关系的故障现象。
7. 输出格式（严格一行一个）：
   实体名称: <名称>, 实体类别: <类别>
8. 示例：
   实体名称: 电源无法接通, 实体类别: 故障现象与报警
   实体名称: ALM401, 实体类别: 故障现象与报警
   实体名称: 电源无法接通 & ALM401, 实体类别: 逻辑与
   实体名称: 主轴过载 & 驱动器高温, 实体类别: 逻辑与"""

    prompt = f"""请从以下<{domain}>技术文档片段中提取实体，并严格遵守规则：

<实体提取规则>
1. 实体类别及定义：
{entity_defs}

2. 约束：
- 每个实体名称≤20个字符（逻辑与实体若超长可适当精简，如“A & B等”）
- 必须符合领域专业性
- 禁止抽取无法独立指代具体实体的抽象词
- 禁止抽取泛指类词汇未带限定
- 禁止抽取纯动词或动词化结构
- 对于“逻辑与”类实体，仅当原文明确描述多个故障现象共同导致另一故障时提取，且名称由这些故障现象组合而成

3. 输出格式（严格一行一个）：
实体名称: <名称>, 实体类别: <类别>

4. 示例：
实体名称: 电源无法接通, 实体类别: 故障现象与报警
实体名称: ALM401, 实体类别: 故障现象与报警
实体名称: 主轴驱动器过热, 实体类别: 故障现象与报警
实体名称: 电源无法接通 & ALM401, 实体类别: 逻辑与
实体名称: 编码器信号丢失 & 伺服使能无效, 实体类别: 逻辑与

<待分析文本>
{chunk_content}
"""
    return prompt, context

    

def generate_relation_prompt_and_context_second(chunk_name, chunk_content: str, entities):
    """
    entities: List[dict] with keys: entity_name, entity_type
    """
    domain = chunk_name.split('_')[0]

    context = f"""你是一位资深的"{domain}"领域专家，特别擅长从技术文档中识别故障现象之间的因果关系以及故障现象与逻辑组合之间的关联。
当前任务需要严格遵循以下规则：
1. 关系必须基于文本中的明确表达（因果动词、并列组合、顺序逻辑等）
2. 每个关系必须连接两个已识别实体
3. 所有关系动词应来自文本中的明确含义，可以适度归纳总结（例如“A导致B”可归纳为“导致”）
4. 不允许虚构关系或凭空假设（必须在上下文中有依据）
5. 必须严格使用提供的实体和关系类型"""

    # 只保留三类关系
    predefined_relations = """
<实体类型关系参考框架>
本任务仅提取以下三类关系，其他关系一律忽略：

1. 故障现象 → 逻辑与 (Relation: 参与组合)
定义：当多个故障现象（实体类型为“故障现象与报警”）共同导致另一个故障时，每个故障现象与该“逻辑与”实体之间的关系。
典型动词：同时发生、共同出现、一起发生、组合、与…结合、并列出现等归纳为“参与组合”
方向：故障现象在前，逻辑与在后
示例：<电源无法接通, 参与组合, 与, 逻辑与实体>
说明：仅当文本中存在明确的“A和B同时发生导致C”或类似表达时提取此关系

2. 逻辑与 → 故障现象 (Relation: 组合导致)
定义：由多个故障现象组合而成的“逻辑与”实体所导致的结果故障现象（实体类型为“故障现象与报警”）。
典型动词：导致、引起、造成、触发、产生等归纳为“导致”
方向：逻辑与在前，故障现象在后
示例：<逻辑与实体, 组合导致, 导致, 系统死机>
说明：必须与关系1成对出现，描述组合结果

3. 故障现象 → 故障现象 (Relation: 触发)
定义：单个故障现象直接导致另一个故障现象的单步因果关系。
典型动词：导致、引起、造成、触发、产生、引发、源于、由…引起等归纳为“触发”
方向：原因故障在前，结果故障在后
示例：<熔断器烧断, 触发, 导致, 电源无法接通>
说明：文本中必须明确描述A→B的因果链

注意：所有关系的具体动词应从文本中提取最贴近的表达（如“导致”“引起”“同时出现”等），若无法精确提取可使用上述推荐动词。
"""

    entity_list = '\n'.join([f"- {e['entity_name']} ({e['entity_type']})" for e in entities]) or "(无实体，若无实体请直接输出空)"

    prompt = f"""请从以下<{domain}>技术文档片段中，基于提供的实体列表，提取上述三类关系（参与组合、组合导致、触发）：

<实体列表>
{entity_list}

<关系规范>
{predefined_relations}

<关系提取规则>
1. 每个关系必须在文本中能找到明确语义或上下文逻辑
2. 输出四元组格式如下（严格一行一个）：
<实体1, 关系类型, 具体动词, 实体2>

3. 示例（假设实体列表包含：电源无法接通、ALM401、主轴过载、逻辑与_电源ALM等）：
<电源无法接通, 参与组合, 同时发生, 逻辑与_电源ALM>
<ALM401, 参与组合, 同时发生, 逻辑与_电源ALM>
<逻辑与_电源ALM, 组合导致, 导致, 主轴过载>
<熔断器烧断, 触发, 导致, 电源无法接通>

<待分析文本>
{chunk_content}
"""
    return prompt, context